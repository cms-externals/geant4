void BeamTestPhysicsList::ConstructParticle()
{
  // pseudo-particles
  G4Geantino::GeantinoDefinition();
  G4ChargedGeantino::ChargedGeantinoDefinition();

  // gamma
  G4Gamma::GammaDefinition();

  // leptons
  G4Electron::ElectronDefinition();
  G4Positron::PositronDefinition();
  G4MuonPlus::MuonPlusDefinition();
  G4MuonMinus::MuonMinusDefinition();

  G4NeutrinoE::NeutrinoEDefinition();
  G4AntiNeutrinoE::AntiNeutrinoEDefinition();
  G4NeutrinoMu::NeutrinoMuDefinition();
  G4AntiNeutrinoMu::AntiNeutrinoMuDefinition();  

  // mesons
  G4PionPlus::PionPlusDefinition();
  G4PionMinus::PionMinusDefinition();
  G4PionZero::PionZeroDefinition();
  G4Eta::EtaDefinition();
  G4EtaPrime::EtaPrimeDefinition();
  G4KaonPlus::KaonPlusDefinition();
  G4KaonMinus::KaonMinusDefinition();
  G4KaonZero::KaonZeroDefinition();
  G4AntiKaonZero::AntiKaonZeroDefinition();
  G4KaonZeroLong::KaonZeroLongDefinition();
  G4KaonZeroShort::KaonZeroShortDefinition();

  // barions
  G4Proton::ProtonDefinition();
  G4AntiProton::AntiProtonDefinition();
  G4Neutron::NeutronDefinition();
  G4AntiNeutron::AntiNeutronDefinition();

  // ions
  G4Deuteron::DeuteronDefinition();
  G4Triton::TritonDefinition();
  G4Alpha::AlphaDefinition();
  G4GenericIon::GenericIonDefinition();
}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

void BeamTestPhysicsList::ConstructProcess()
{
  // Transportation
  //
  AddTransportation();

  // Electromagnetic physics list
  //
  emPhysicsList->ConstructProcess();
}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

void BeamTestPhysicsList::AddPhysicsList(const G4String& newname)
{
  if(0 < verboseLevel) {
    G4cout << "PhysicsList::AddPhysicsList: <" << fName << ">" << G4endl;
  }

  if (fName == newname) return;

  if (newname == "emstandard_opt0"){
    delete emPhysicsList;
    fName = newname;
    emPhysicsList = new G4EmStandardPhysics();

  } else if (newname == "emstandard_opt1"){
    delete emPhysicsList;
    fName = newname;
    emPhysicsList = new G4EmStandardPhysics_option1();

  } else if (newname == "emstandard_opt2"){
    delete emPhysicsList;
    fName = newname;
    emPhysicsList = new G4EmStandardPhysics_option2();

  } else if (newname == "emstandard_opt3"){
    delete emPhysicsList;
    fName = newname;
    emPhysicsList = new G4EmStandardPhysics_option3();

  } else if (newname == "empenelope"){
    delete emPhysicsList;
    fName = newname;
    emPhysicsList = new G4EmPenelopePhysics();

  } else if (newname == "emlivermore"){
    delete emPhysicsList;
    fName = newname;
    emPhysicsList = new G4EmLivermorePhysics();

  } else {

    G4cout << "PhysicsList::AddPhysicsList: <" << newname << ">"
	   << " is not defined" << G4endl;
  }
}

