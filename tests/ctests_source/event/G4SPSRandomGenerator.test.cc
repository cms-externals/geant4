// Test Fixture to encapsulate fixed random sequence and common testing algorithm
class G4SPSRandomGeneratorTest : public ::testing::TestWithParam<G4SPSBiasAxis>
{
  protected:

    void SetUp() override
    {
      // Initialize with N random numbers uniformly increasing from 0 to 1
      const size_t length = 100;
      const double step = 1.0 / length;
      mock_rndm.reserve(length);
      for (size_t i = 0; i < length; ++i)
      {
        // At present, biasing breaks for a true-zero RN...
        mock_rndm.push_back((i + 0.5) * step);
      }

      // Install fixed sequence in CLHEP Engine used in Geant4
      engine = new G4FixedRandomEngine(mock_rndm);
      CLHEP::HepRandom::setTheEngine(engine);
    }

    void TearDown() override { delete engine; }

    void RunOver(const std::vector<G4ThreeVector>& bias,
                 std::function<G4double(G4double)> expected_rndm,
                 std::function<G4double(G4double)> expected_weight)
    {
      const auto& axis = GetParam();

      // Fill weights
      for (const auto& bp : bias)
      {
        axis.SetBias(sps, bp);
      }

      // Compare actual/expected
      for (const auto& input_rndm : mock_rndm)
      {
        SCOPED_TRACE(G4String("input_rndm evaluates to ") + std::to_string(input_rndm));
        double actual_rndm = axis.GenRand(sps);
        EXPECT_NEAR(actual_rndm, expected_rndm(input_rndm), kPrecision);
        EXPECT_NEAR(sps.GetBiasWeight(), expected_weight(actual_rndm), kPrecision);
      }
    }

    std::vector<double> mock_rndm;
    G4FixedRandomEngine* engine = nullptr;
    G4SPSRandomGenerator sps;
};

