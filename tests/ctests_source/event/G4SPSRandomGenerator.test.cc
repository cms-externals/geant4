// Uniform bias: all bins have the same weight
std::vector<G4ThreeVector> UniformBias(size_t n_bins, double weight)
{
  std::vector<G4ThreeVector> bias;
  double step = 1.0 / n_bins;
  bias.emplace_back(0.0, 0.0, 0.0);  // lower edge, ignored
  for (size_t i = 1; i <= n_bins; ++i)
  {
    bias.emplace_back(i * step, weight, 0.0);
  }
  return bias;
}

