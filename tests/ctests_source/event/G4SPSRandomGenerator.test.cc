  // Mock a Gaussian-like function
  // - 5 bins, weight peaking in 3rd (central) bin
  // We need to include the low edge!
  const std::vector<G4ThreeVector> bias = {{0.0, 0.0}, {0.2, 1.0}, {0.4, 2.0},
                                           {0.6, 4.0}, {0.8, 2.0}, {1.0, 1.0}};
  // Total area is 10, so CDF is:
  const std::vector<G4ThreeVector> cdf = {
    {0.2, 0.1}, {0.4, 0.3}, {0.6, 0.7}, {0.8, 0.9}, {1.0, 1.0}};
  // For a rndm falling in bin i of CDF, expected weight is binWidth(i)/NORM{biasH(i)} so:
  const std::vector<G4ThreeVector> weights = {
    {0.2, 0.2 / 0.1}, {0.4, 0.2 / 0.2}, {0.6, 0.2 / 0.4}, {0.8, 0.2 / 0.2}, {1.0, 0.2 / 0.1}};

