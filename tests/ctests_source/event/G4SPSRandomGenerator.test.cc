// Helper for calculating expected rndm and weights
// This is a little circular as this essentially does what the GenRand functions
// do, albeit with a different implementation. The current need for this is
// checking reproducibility whilst refactoring, so this is acceptable for now.
// It also requires manual calculation of the CDF and weights vector.
struct G4SPSExpectedCalculator
{
    double expected_weight(double rndm) const
    {
      for (const auto& bin : weights_)
      {
        if (rndm < bin.x()) return bin.y();
      }
      return -1.0;
    }

    double expected_rndm(double known_rndm) const
    {
      // 1. Find bin of cdf in which known_rndm lies (y_lower, y_upper)
      auto bin = std::find_if(cdf_.begin(), cdf_.end(), [&known_rndm](const auto& cdf_bin) {
        return known_rndm < cdf_bin.y();
      });

      // Return "impossible" rndm if out of range.
      if (bin == cdf_.end()) return -1.0;

      // Linear interpolate back to x
      G4double x_upper = (*bin).x();
      G4double y_upper = (*bin).y();
      G4double x_lower = 0.0;
      G4double y_lower = 0.0;
      if (bin != cdf_.begin())
      {
        auto lower = (bin - 1);
        x_lower = (*lower).x();
        y_lower = (*lower).y();
      }

      return x_lower + (x_upper - x_lower) * (known_rndm - y_lower) / (y_upper - y_lower);
    };

    // Lambda-ize expected_weight for use in fixtures
    auto expected_weight_fn() const
    {
      return [this](G4double r) {
        return this->expected_weight(r);
      };
    }

    // Lambda-ize expected_rndm for use in fixtures
    auto expected_rndm_fn() const
    {
      return [this](G4double r) {
        return this->expected_rndm(r);
      };
    }

    const std::vector<G4ThreeVector>& cdf_;
    const std::vector<G4ThreeVector>& weights_;
};

