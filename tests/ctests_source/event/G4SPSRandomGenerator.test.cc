TEST_P(G4SPSRandomGeneratorTest, SingleBinBiasOutputRange)
{
  // Single bin bias basically compresses rngs to bin low-high edge
  // Weight is binwidth
  // Take 12 uniform bins with bin 5 as the single filled one (arbitrary weight)
  // - Bin low edge = 1./12.*5
  // - Bin width reduces to bin width for single bin = 1./12.
  const size_t n_bins = 12;
  const size_t selected_bin = 5;
  const G4double selected_bin_width = 1.0 / n_bins;
  const G4double selected_bin_low_edge = selected_bin * selected_bin_width;

  const G4double expected_bin_weight = selected_bin_width;
  const G4double selected_weight = 0.3654;

  // We create two points (single bin) as the non-zero elements are not needed here
  auto bias = std::vector<G4ThreeVector>{
    {selected_bin_low_edge, 0.0}, {selected_bin_low_edge + selected_bin_width, selected_weight}};

  auto expected_weight = [&](G4double) {
    return expected_bin_weight;
  };
  auto expected_rndm = [&](G4double r) {
    return selected_bin_low_edge + selected_bin_width * r;
  };

  SCOPED_TRACE(::testing::UnitTest::GetInstance()->current_test_info()->name());
  this->RunOver(bias, expected_rndm, expected_weight);
}

