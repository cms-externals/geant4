TEST_P(G4SPSRandomGeneratorTest, UnbiasedOutputRange)
{
  // Without biasing, must get passthrough with no modification and exact numbers
  const auto& axis = GetParam();
  for (const auto& input_rndm : mock_rndm)
  {
    double actual_rndm = axis.GenRand(sps);
    EXPECT_EQ(actual_rndm, input_rndm);
    EXPECT_EQ(sps.GetBiasWeight(), 1.0);
  }
}

